export const PRODUCT_GUIDE = `# ZnxStudio Documentation

ZnxStudio is an IDE for Zornux and Zoijs projects. This guide covers the main workbench surfaces and the quickest way to find IDE features.

## Getting started

1. Use **File → New Project…** to create a project, or **File → Open Folder…** to open an existing one.
2. Browse and edit files from the Explorer in the Activity Bar.
3. Use **Run → Run Without Debugging** to run the active project, or **Run → Start Debugging** to launch a debug session.
4. Open **View → Open Panel…** to find output, testing, logs, terminal, and other tool panels.

## Navigation

- **Go → Go to File…** quickly opens a file by name.
- **Go → Search Everywhere…** searches across IDE resources.
- **Go → Find in Files** searches project text and supports replacement.
- Open the Command Palette to discover every registered command.

## Editing

- **Edit → Find in File** opens the active editor's search widget.
- **File → Save** saves the active file; **Save All** saves every dirty file.
- The Selection menu contains multi-cursor and code-folding actions.

## Run, debug, and test

- **Run → Run Script…** lists scripts declared by the current ZnxStudio project.
- Debug actions such as Continue, Step Over, Step Into, and Step Out are under **Run → Debug**.
- Test Explorer, Coverage, Mocks, and Continuous Testing are under **Run → Test**.

## Panels and workspaces

Use the View menu to show or hide the Side Bar, Activity Bar, bottom Panel, and Status Bar. Purpose-built workspaces group tools for coding, debugging, testing, databases, security, performance, AI, cloud, documentation, architecture, Git, and extensions.

## AI features

Use **AI → Configure AI…** to select and configure a provider. The AI menu then provides chat, review, debugging assistance, test generation, documentation, architecture analysis, and refactoring tools.

## More help

- Run **Help: Welcome** from the Command Palette to return to the start screen.
- Run **Learn: Show Learning Center** for tutorials and guided material.
- **Help → Workspace README** opens the README belonging to the current project.
`;
